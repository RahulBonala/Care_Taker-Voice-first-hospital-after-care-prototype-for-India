'use strict';
// npm run review-sheet: writes docs/LANGUAGE_REVIEW.md, a sheet a native speaker can tick line by line.
// One section per language other than English, with every call line, slot name, app wording and health feedback line.
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const DIR = path.join(ROOT, 'server', 'lang');
const OUT = path.join(ROOT, 'docs', 'LANGUAGE_REVIEW.md');
const GROUPS = [
  ['lines', 'Call lines (spoken on the phone)'],
  ['slots', 'Dose times'],
  ['ui', 'App wording'],
  ['feedback', 'Health feedback'],
];

const langs = fs.readdirSync(DIR).filter((f) => f.endsWith('.json')).sort()
  .map((f) => JSON.parse(fs.readFileSync(path.join(DIR, f), 'utf8')));
const en = langs.find((l) => l.code === 'en');
const others = langs.filter((l) => l.code !== 'en');

// Table cells: one line, pipes escaped, so a long sentence never breaks the table.
const cell = (s) => String(s === undefined || s === null || s === '' ? '(missing)' : s).replace(/\r?\n/g, ' ').replace(/\|/g, '\\|');

const out = [];
out.push('# Language review sheet', '');
out.push('Generated by `npm run review-sheet` from `server/lang/*.json`. Do not edit this file by hand: fix the language file and run the script again.', '');
out.push('## For the reviewer', '');
out.push('Thank you for checking a language. Read each line in the "Current text" column next to the English, then tick the last column.', '');
out.push('Check each line for:', '');
out.push('1. **Natural wording.** It should sound like a polite hospital staff member speaking to an older patient, not a word-by-word translation.');
out.push('2. **Politeness.** Use the respectful form of "you" that a patient would expect from a hospital.');
out.push('3. **No medical advice.** A line states facts only. It never tells the patient to eat, walk, rest, take or change a medicine. Anything outside a range says a nurse or the care team will look at it.');
out.push('4. **Placeholders kept.** Words in curly brackets, such as `{name}`, `{slot}`, `{time}` or `{steps}`, are filled in by the app. Keep them exactly as written, in any position that reads naturally. Numbers stay as digits.');
out.push('5. **Short.** Call lines stay under 15 words. No long dash characters: use a comma, colon or full stop.', '');
out.push('How to mark a line:', '');
out.push('- Put `yes` in the OK? column if the line is right.');
out.push('- If it is wrong, write the better wording in the OK? column, or send it to the team with the key name.', '');
out.push('When every line in a language is ticked, open `server/lang/<code>.json` and set `"reviewedByNativeSpeaker": true`. The app then stops showing the "Language under review" tag for that language.', '');
out.push('## Languages', '');
out.push('| Code | Language | Reviewed by a native speaker |');
out.push('| --- | --- | --- |');
for (const L of others) out.push(`| ${L.code} | ${cell(L.name)} (${cell(L.nativeName)}) | ${L.reviewedByNativeSpeaker ? 'yes' : 'not yet'} |`);
out.push('');

for (const L of others) {
  out.push(`## ${L.name} (${L.nativeName}), \`${L.code}\``, '');
  out.push(`File: \`server/lang/${L.code}.json\`. Reviewed by a native speaker: ${L.reviewedByNativeSpeaker ? 'yes' : 'not yet'}.`, '');
  for (const [group, title] of GROUPS) {
    const keys = Object.keys(en[group] || {});
    if (!keys.length) continue;
    out.push(`### ${title}`, '');
    out.push('| Key | English | Current text | OK? |');
    out.push('| --- | --- | --- | --- |');
    for (const k of keys) out.push(`| \`${group}.${k}\` | ${cell(en[group][k])} | ${cell((L[group] || {})[k])} |  |`);
    out.push('');
  }
}

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, out.join('\n').replace(/\n+$/, '\n'));
const rows = others.length * GROUPS.reduce((a, [g]) => a + Object.keys(en[g] || {}).length, 0);
console.log(`Wrote ${path.relative(ROOT, OUT)}: ${others.length} languages, ${rows} lines to review.`);
